#!/usr/bin/env python3
"""Build the combined card/settings update or an isolated 24H/12H native review.

Copies tracked app files only; never installs, pushes, publishes or accesses keys.
The review uses the production JS formatter to create deterministic C mock data.
"""
import argparse,json,os,shutil,subprocess,zipfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--production',action='store_true');p.add_argument('--format',choices=['24H','12H'],default='24H');args=p.parse_args()
name='settings-cards-production' if args.production else 'settings-cards-'+args.format.lower()
project=ROOT/'build'/name;project.mkdir(parents=True,exist_ok=True)
for folder in ['src','resources']:
    if (project/folder).exists():shutil.rmtree(project/folder)
files=subprocess.check_output(['git','ls-files','-z','src','resources','package.json','package-lock.json','wscript'],cwd=ROOT).decode().split('\0')
for relative in filter(None,files):
    target=project/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(ROOT/relative,target)
tools=Path(os.environ.get('PEBBLE_TOOLS_DIR',Path.home()/'Developer/pebble-flight/.tools'))
env=dict(os.environ);env['PATH']=str(tools/'node/bin')+':'+str(tools/'bin')+':'+env.get('PATH','')
def s(value):return json.dumps(value,ensure_ascii=True)
if not args.production:
    package=json.loads((project/'package.json').read_text());package['pebble'].update(displayName='Jetebble Review',uuid='b8c70788-473f-4d58-8b65-a772fa1cb09b',capabilities=[])
    (project/'package.json').write_text(json.dumps(package,indent=2)+'\n')
    config=project/'src/c/prototype_config.h';config.write_text(config.read_text().replace('#define PEBBLE_MOCK_DATA 0','#define PEBBLE_MOCK_DATA 1'))
    (project/'src/pkjs/index.js').write_text('// Inert offline review companion. No services or settings.\n')
    js="console.log(JSON.stringify(require('./test/fixtures/settings_review_flights')(%s)));"%s(args.format)
    frames=json.loads(subprocess.check_output([str(tools/'node/bin/node'),'-e',js],cwd=ROOT,text=True))
    def field(frame,key,state):return '{%d,%s}'%(frame[state],s(frame[key]))
    def endpoint(frame,dep):
        t='DEP' if dep else 'ARR';prefix='DEPARTURE' if dep else 'ARRIVAL'
        values=[frame['UI_'+t+'_SCHEDULED'],frame[prefix+'_TIME'],frame['UI_'+t+'_DATE'],frame['UI_'+t+'_ZONE'],frame['UI_'+t+'_OFFSET'],frame['UI_'+t+'_KIND'],bool(frame['UI_'+t+'_DELAY_KNOWN']),frame['UI_'+t+'_DELAY'],frame['UI_'+t+'_SCHEDULED_DATE'],frame['UI_'+t+'_SCHEDULED_ZONE']]
        time='{'+','.join('true' if v is True else 'false' if v is False else str(v) if isinstance(v,int) else s(v) for v in values)+'}'
        facility=field(frame,'DEPARTURE_GATE','UI_DEP_GATE_STATE') if dep else field(frame,'UI_BAGGAGE','UI_BAGGAGE_STATE')
        return '{'+','.join([s(frame['ORIGIN' if dep else 'DESTINATION']),s(frame['UI_'+t+'_NAME']),time,field(frame,prefix+'_TERMINAL','UI_'+t+'_TERMINAL_STATE'),facility])+'}'
    flights=[]
    for f in frames:
        booking='{'+','.join([field(f,'BOOKING_CODE','UI_BOOKING_STATE'),field(f,'SEAT_NUMBER','UI_SEAT_STATE'),'SEAT_WINDOW','true'])+'}'
        flights.append('{'+','.join([s(f['FLIGHT_NUMBER']),s(f['FLIGHT_DATE']),str(f['UI_STATUS']),str(f['UI_PROGRESS']),endpoint(f,True),endpoint(f,False),booking,'false'])+'}')
    source='#include "../prototype_config.h"\n#if PEBBLE_UI_PROTOTYPE && PEBBLE_MOCK_DATA\n#include "flight_model.h"\n// Synthetic fixtures generated by the actual phone time formatter.\nstatic const Flight flights[]={\n'+',\n'.join(flights)+'\n};\nsize_t mock_flight_count(void){return 5;}\nconst Flight *mock_flight_at(size_t i){return i<5?&flights[i]:NULL;}\n#endif\n'
    (project/'src/c/prototype/mock_flights.c').write_text(source)
    (project/'README.md').write_text('Jetebble Review: native Pebble C SDK / Emery / SDK metadata 3.\nOffline synthetic five-flight review in '+args.format+'. No credentials or live services.\nSeparate UUID; coexists with Jetebble. Up/Down: select/page; Select: open/note; Back: list.\nAny button skips the existing startup animation. Hold Select on the list: empty demo.\n')
    with zipfile.ZipFile(ROOT/('build/jetebble-review-'+args.format.lower()+'-source.zip'),'w',zipfile.ZIP_DEFLATED) as archive:
        for f in sorted(project.rglob('*')):
            rel=f.relative_to(project)
            if f.is_file() and not any(x in ('build','node_modules','.tools') for x in rel.parts) and not rel.name.startswith('.lock'):archive.write(f,rel)
subprocess.run([str(tools/'bin/pebble'),'clean'],cwd=project,env=env,check=True)
subprocess.run([str(tools/'bin/pebble'),'build'],cwd=project,env=env,check=True)
out=ROOT/('build/jetebble-0.7.8.pbw' if args.production else 'build/jetebble-review-'+args.format.lower()+'.pbw')
shutil.copyfile(project/'build'/(name+'.pbw'),out);print(out)
